"""
Model Training Script
Train Isolation Forest models for KYC, Business, and Transaction anomaly detection

This script has been updated to work with the actual data structure generated by
generate_synthetic_data.py. It supports training multiple model types:

1. KYC Model: Trains on customer demographic and identity data
2. Business Model: Trains on business information and financial data
3. Transaction Model: Trains on transaction patterns and behaviors
4. Merged Model: Combines KYC and Business features for comprehensive analysis

Usage Examples:
    # Train all models (hackathon demo mode)
    python train_models.py

    # Train specific models
    python train_models.py --train-kyc --kyc-data data/raw/kyc_training_data.csv
    python train_models.py --train-business --business-data data/raw/business_training_data.csv
    python train_models.py --train-transaction --transaction-data data/raw/transaction_training_data.csv
    python train_models.py --train-merged --merged-data data/raw/kyc_business_training_data.csv

    # Train multiple models
    python train_models.py --train-kyc --train-business --kyc-data data/raw/kyc_training_data.csv --business-data data/raw/business_training_data.csv
"""
